import AppKit

/// Окно питомца, которое AppKit не двигает по своему усмотрению.
///
/// По умолчанию система подтягивает любое окно вниз, чтобы его верх не уходил
/// выше видимой области экрана — так у обычных окон остаётся доступен
/// заголовок. Питомцу это ставит невидимый потолок: при высоте окна 98
/// пунктов и видимой области до 949 его лапы не поднимаются выше ~865.
///
/// Последствий два, и оба выглядели как ошибки движка:
/// мышью питомца нельзя было поднять выше этой черты, а забравшись на
/// заголовок окна выше потолка, он рисовался ниже своей полки — то самое
/// «сидит в воздухе».
final class PetPanel: NSPanel {
    override func constrainFrameRect(_ frameRect: NSRect, to screen: NSScreen?) -> NSRect {
        frameRect
    }
}
